/*
 * tif2obj.c — Standalone TIFF-to-OBJ marching cubes converter
 *
 * Loads a binary TIFF volume, pads with 1 voxel of zeros, runs marching cubes,
 * shifts vertices back by -1, and writes an OBJ file.
 *
 * Usage: tif2obj <input.tif> <output.obj> [--fg-val N]
 *
 * --fg-val N: only mesh voxels with this value (default: any nonzero).
 *             Use --fg-val 1 for multi-label GT TIFFs where 2=ignore.
 *
 * Build: gcc -O2 -o tif2obj scripts/tif2obj.c -ltiff -lm
 *
 * No dependencies on pipeline modules. Only needs libtiff + libm.
 */

